def test_init_installs_the_five_hooks_by_config_and_is_idempotent(env: Env) -> None:
    repo = env.repo
    first = repo.cli("init")
    assert first.code == 0 and "git config hooks: pre-commit, pre-push" in first.err
    before = config_hooks(repo)
    assert len(before) == 10  # a command and an event per hook
    for event in hooks.EVENTS:
        assert f"hook.nbp-git-safe-{event}.command" in "\n".join(before)
        assert hooks.hook_name(event) in repo.sh("hook", "list", event).split()
    assert not any((repo.path / ".git" / "hooks" / e).exists() for e in hooks.EVENTS)
    assert repo.cli("init").code == 0
    assert config_hooks(repo) == before  # idempotent: no duplicate events or commands


def test_hook_command_is_a_quoted_oneliner_for_this_interpreter(env: Env) -> None:
    env.repo.cli("init")
    command = env.repo.sh("config", "--local", "hook.nbp-git-safe-pre-commit.command").strip()
    assert command == hooks.hook_command("pre-commit")
    assert command.endswith(" -I -m nbp_git_safe hook pre-commit")
    assert command.startswith("'") and " -I " in command  # quoted path, isolated mode


@pytest.mark.parametrize(
    "script", [FOREIGN_HAND_WRITTEN, FOREIGN_FRAMEWORK], ids=["own", "framework"]
)
def test_foreign_hooks_in_the_hooks_dir_run_alongside_and_stay_untouched(
    env: Env, script: str
) -> None:
    repo = env.repo
    hooks_dir = repo.path / ".git" / "hooks"
    pre = write_hook(hooks_dir, "pre-commit", script)
    post = write_hook(hooks_dir, "post-commit", script)
    digests = {pre: sha(pre), post: sha(post)}
    assert repo.cli("init").code == 0
    assert {pre: sha(pre), post: sha(post)} == digests
    repo.sh("add", "-A")
    result = commit(repo, "both hooks run")
    assert result.returncode == 0, result.stderr
    assert foreign_runs(repo) == 2  # the foreign pre-commit and post-commit both ran ...
    assert env.has_vault()  # ... and so did ours (post-commit sealed)
    # ours still blocks even though the foreign hook says yes
    repo.write("reports/blocked.csv", "x")
    repo.sh("add", "-f", "reports/blocked.csv")
    assert commit(repo, "nope").returncode != 0
    repo.sh("restore", "--staged", "--", "reports/blocked.csv")
    prune_unreachable(repo)
    # a foreign hook that fails blocks too: we do not swallow it
    write_hook(hooks_dir, "pre-commit", "#!/bin/sh\nexit 1\n")
    assert commit(repo, "foreign says no", "--allow-empty").returncode != 0
    write_hook(hooks_dir, "pre-commit", script)
    # uninstall removes ours only
    assert repo.cli("uninstall", "--yes").code == 0
    assert {pre: sha(pre), post: sha(post)} == digests
    assert config_hooks(repo) == []
    repo.assert_no_leak(env.bare)


def test_husky_style_hooks_path_is_respected_and_never_written_to(env: Env) -> None:
    repo = env.repo
    husky = repo.path / ".husky"
    script = write_hook(husky, "pre-commit", FOREIGN_HAND_WRITTEN)
    repo.sh("config", "--local", "core.hooksPath", ".husky")
    digest = sha(script)
    result = repo.cli("init")
    assert result.code == 0 and "git config hooks" in result.err
    assert sorted(p.name for p in husky.iterdir()) == ["pre-commit"]  # nothing added there
    assert sha(script) == digest
    repo.sh("add", "-A")
    assert commit(repo, "with husky").returncode == 0
    assert foreign_runs(repo) == 1 and env.has_vault()
    repo.write("reports/x.csv", "x")
    repo.sh("add", "-f", "reports/x.csv")
    assert commit(repo, "blocked").returncode != 0
    repo.sh("restore", "--staged", "--", "reports/x.csv")
    prune_unreachable(repo)
    report = repo.cli("doctor")
    assert report.code == 0 and "core.hooksPath is set" in report.out
    assert repo.cli("uninstall", "--yes").code == 0
    assert sorted(p.name for p in husky.iterdir()) == ["pre-commit"] and sha(script) == digest


# ------------------------------------------------------------------- shim fallback


@pytest.fixture
def no_config_hooks(monkeypatch: pytest.MonkeyPatch) -> None:
    """Pretend git is too old for hooks by config (``init`` then falls back to shims). The hooks
    themselves run in separate processes with the real code."""
    monkeypatch.setattr(hooks, "MIN_GIT", (99, 0))


def test_shim_fallback_installs_only_where_nothing_exists(env: Env, no_config_hooks: None) -> None:
    repo = env.repo
    hooks_dir = repo.path / ".git" / "hooks"
    foreign = write_hook(hooks_dir, "pre-push", FOREIGN_HAND_WRITTEN)
    digest = sha(foreign)
    result = repo.cli("init")
    assert result.code == 0
    assert "hook-file shims: pre-commit, post-commit, post-merge, post-checkout" in result.err
    assert "NOT installed: pre-push" in result.err
    assert "a hook file that is not ours exists" in result.err
    assert sha(foreign) == digest  # never overwritten
    assert config_hooks(repo) == []
    for event in ("pre-commit", "post-commit", "post-merge", "post-checkout"):
        text = (hooks_dir / event).read_text()
        assert hooks.is_our_shim(text, event) and text == hooks.shim_text(event)
    statuses = {s.event: s for s in hooks.inspect_hooks(*_git_repo(repo))}
    assert statuses["pre-commit"].ok and statuses["pre-commit"].mechanism == "shim"
    assert not statuses["pre-push"].ok and statuses["pre-push"].foreign_file
    before = {e: sha(hooks_dir / e) for e in ("pre-commit", "post-commit")}
    assert repo.cli("init").code == 0  # idempotent
    assert {e: sha(hooks_dir / e) for e in before} == before


def _git_repo(repo: NbpRepo):  # type: ignore[no-untyped-def]
    from nbp_git_safe.gitutil import discover

    found, git = discover(repo.path, repo.git.env)
    return git, found


def test_shim_hooks_really_guard_and_seal(env: Env, no_config_hooks: None) -> None:
    repo = env.repo
    assert repo.cli("init").code == 0
    repo.sh("add", "-A")
    assert commit(repo, "baseline via shims").returncode == 0, "shim pre-commit must pass"
