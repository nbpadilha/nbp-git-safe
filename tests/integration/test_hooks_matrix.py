def test_uninstall_removes_only_shims_of_our_exact_shape(env: Env, no_config_hooks: None) -> None:
    repo = env.repo
    hooks_dir = repo.path / ".git" / "hooks"
    assert repo.cli("init").code == 0
    edited = hooks_dir / "post-merge"
    edited.write_bytes(edited.read_bytes() + b"echo my own addition\n")  # no longer our shape
    digest = sha(edited)
    assert repo.cli("init").code == 0
    assert sha(edited) == digest  # a modified shim is treated as foreign, not repaired
    assert repo.cli("uninstall", "--yes").code == 0
    assert not (hooks_dir / "pre-commit").exists() and not (hooks_dir / "post-commit").exists()
    assert edited.exists() and sha(edited) == digest


def test_with_shim_flag_adds_shims_next_to_config_hooks_and_uninstall_takes_both(env: Env) -> None:
    repo = env.repo
    result = repo.cli("init", "--shim")
    assert result.code == 0
    hooks_dir = repo.path / ".git" / "hooks"
    assert all((hooks_dir / e).exists() for e in hooks.EVENTS)
    assert len(config_hooks(repo)) == 10
    assert repo.cli("init").code == 0  # without the flag the shims we own are dropped again
    assert not any((hooks_dir / e).exists() for e in hooks.EVENTS)
    repo.cli("init", "--shim")
    out = repo.cli("uninstall", "--yes").out
    assert "hook shim removed" in out and "config hook removed" in out
    assert config_hooks(repo) == [] and not any((hooks_dir / e).exists() for e in hooks.EVENTS)


