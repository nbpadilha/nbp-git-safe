def test_uninstall_confirmation_flow_and_what_it_never_touches(
    env: Env, monkeypatch: pytest.MonkeyPatch
) -> None:
    repo = env.repo
    assert repo.cli("init").code == 0
    repo.sh("add", "-A")
    assert commit(repo, "base").returncode == 0
    tip = env.tip()
    files = {
        p.relative_to(repo.path).as_posix(): p.read_bytes()
        for p in (repo.path / "reports").rglob("*")
        if p.is_file()
    }
    refused = repo.cli("uninstall")  # no terminal, no --yes
    assert refused.code == 1 and "confirmation" in refused.err and config_hooks(repo)

    class FakeTty:
        def isatty(self) -> bool:
            return True

    monkeypatch.setattr(sys, "stdin", FakeTty())
    monkeypatch.setattr("builtins.input", lambda _prompt="": "no")
    wrong = repo.cli("uninstall")
    assert wrong.code == 1 and "not confirmed" in wrong.err and config_hooks(repo)
    monkeypatch.setattr("builtins.input", lambda _prompt="": "uninstall")
    done = repo.cli("uninstall")
    assert done.code == 0 and "exclude block removed" in done.out
    assert config_hooks(repo) == []
    assert env.tip() == tip  # the vault branch is untouched ...
    assert {
        p.relative_to(repo.path).as_posix(): p.read_bytes()
        for p in (repo.path / "reports").rglob("*")
        if p.is_file()
    } == files  # ... and so are the plaintext files
    assert "nothing of ours" in repo.cli("uninstall", "--yes").out
    assert "reports/" in repo.sh("status", "--porcelain")  # visible to git again


