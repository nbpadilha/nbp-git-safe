FOREIGN_HAND_WRITTEN = (
    '#!/bin/sh\necho "ran $0" >> "$(git rev-parse --git-dir)/foreign-ran"\nexit 0\n'
)
FOREIGN_FRAMEWORK = (
    "#!/usr/bin/env bash\n"
    "# File generated by pre-commit: https://pre-commit.com\n"
    "# ID: 138fd403232d2ddd5efb44317e38bf03\n"
    'echo "ran framework" >> "$(git rev-parse --git-dir)/foreign-ran"\n'
    "exit 0\n"
)


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_hook(directory: Path, event: str, text: str) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / event
    path.write_bytes(text.encode("utf-8"))
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return path


def foreign_runs(repo: NbpRepo) -> int:
    marker = repo.path / ".git" / "foreign-ran"
    return len(marker.read_text().splitlines()) if marker.exists() else 0


def config_hooks(repo: NbpRepo) -> list[str]:
    out = repo.raw("config", "--local", "--get-regexp", r"^hook\.").stdout
    return [line for line in out.splitlines() if line]


