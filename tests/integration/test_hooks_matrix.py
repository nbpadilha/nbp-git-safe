# ------------------------------------------------------------------- autoUnlock / prompts


def marker_key_command(repo: NbpRepo, marker: Path, *, then: str = "ok") -> None:
    """keyCommand that records that it ran, then behaves like the normal test command."""
    code = (
        "import pathlib, subprocess, sys;"
        f"pathlib.Path({str(marker)!r}).write_text('ran');"
        f"sys.exit(subprocess.call([sys.executable, {str(helpers.KEYCMD)!r}, {then!r}]))"
    )
    repo.set_config("nbp-safe.keyCommand", json.dumps([sys.executable, "-c", code]))


def test_hooks_never_run_the_key_command_by_default(env: Env, tmp_path: Path) -> None:
    repo = env.repo
    marker = tmp_path / "key-command-ran"
    marker_key_command(repo, marker)
    env.agent.stop()  # locked
    assert repo.cli("init").code == 0
    repo.sh("add", "-A")
    result = commit(repo, "locked commit")
    assert result.returncode == 0 and "nbp-git-safe unlock" in result.stderr
    repo.raw("push", "-q", "origin", "main")
    repo.sh("checkout", "-q", "-b", "other")
    assert not marker.exists()  # autoUnlock=false: no hook ever prompts or runs the command


def test_auto_unlock_is_opt_in_and_enables_the_content_check(env: Env, tmp_path: Path) -> None:
    repo = env.repo
    key_env = {helpers.TEST_KEY_ENV: crypto.encode_key(repo.master)}  # the test keyCommand reads it
    marker = tmp_path / "key-command-ran"
    marker_key_command(repo, marker)
    repo.set_config("nbp-safe.autoUnlock", "true")
    env.agent.stop()
    assert repo.cli("init").code == 0
    repo.sh("add", "-A")
    first = commit(repo, "baseline", env=key_env)
    assert first.returncode == 0, first.stderr
    assert marker.exists() and env.has_vault(), first.stderr  # the hook unlocked and sealed
    repo.write("public/c.txt", repo.read(first_protected(repo, ".csv")))
    repo.sh("add", "public/c.txt")
    blocked = commit(repo, "copy", env=key_env)
    assert blocked.returncode != 0 and "same content" in blocked.stderr
    repo.sh("restore", "--staged", "--", "public/c.txt")
    prune_unreachable(repo)
    repo.assert_no_leak(env.bare)


def test_auto_unlock_failure_or_timeout_degrades_to_the_path_check(
    env: Env, tmp_path: Path
) -> None:
    repo = env.repo
    env.agent.stop()
    marker = tmp_path / "ran"
    marker_key_command(repo, marker, then="sleep")
    repo.set_config("nbp-safe.autoUnlock", "true")
    repo.set_config("nbp-safe.keyCommandTimeout", "1")
    assert repo.cli("init").code == 0
    repo.sh("add", "-A")
    slow = commit(repo, "key command hangs")
    assert slow.returncode == 0, slow.stderr
    assert "autoUnlock failed" in slow.stderr and "timed out" in slow.stderr
    marker_key_command(repo, marker, then="exit1")
    repo.write("reports/z.csv", "z")
    repo.sh("add", "-f", "reports/z.csv")
    blocked = commit(repo, "still guarded by path")
    assert blocked.returncode != 0 and "reports/z.csv" in blocked.stderr
    assert "autoUnlock failed" in blocked.stderr


